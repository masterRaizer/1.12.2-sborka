def wrap(text, limit):
    """Mantle wraps book text wider than the visible page (English overflows too), so break lines ourselves."""
    out, line = [], ""
    for word in text.split(" "):
        if line and len(line) + 1 + len(word) > limit:
            out.append(line)
            line = word
        else:
            line = word if not line else line + " " + word
    out.append(line)
    return out


def limit_for(rel):
    # full-width text pages start at the page margin; modifier/accessory/armor pages are indented
    return 43 if rel.startswith(("intro/", "armory/")) and rel != "armory/armor.json" else 41


def main():
    done = 0
    seen = set()
    for root, _, files in os.walk(SRC):
        for f in files:
            if not f.endswith(".json"):
                continue
            rel = os.path.relpath(os.path.join(root, f), SRC).replace("\\", "/")
            seen.add(rel)
            if rel not in T:
                sys.exit("no translation for " + rel)
            with open(os.path.join(root, f), encoding="utf-8") as fh:
                d = json.load(fh)
            t = T[rel]
            if "title" in d:
                d["title"] = t["title"]
            elif "title" in t:
                sys.exit("unexpected title in " + rel)
            if len(d["text"]) != len(t["text"]):
                sys.exit(f"text count mismatch in {rel}: {len(d['text'])} vs {len(t['text'])}")
            # Mantle mis-wraps a "\n" inside a text item, so every line is its own item,
            # separated by {"text": "\n"} items (as the mod's own armor.json does).
            items = []
            for item, ru in zip(d["text"], t["text"]):
                if ru is None:
                    assert item["text"] == "\n", rel
                    items.append(item)
                    continue
                assert item["text"] != "\n", rel
                for n, line in enumerate(wrap(ru, limit_for(rel))):
                    if n:
                        items.append({"text": "\n"})
                    new = {"text": line}
                    if n == 0:
                        new.update({k: v for k, v in item.items() if k != "text"})
                    items.append(new)
            d["text"] = items
            for key in ("effects", "properties"):
                if key in d or key in t:
                    if len(d[key]) != len(t[key]):
                        sys.exit(f"{key} count mismatch in {rel}")
                    d[key] = t[key]
            out = os.path.join(DST, rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with open(out, "w", encoding="utf-8", newline="\n") as fh:
                json.dump(d, fh, ensure_ascii=False, indent=2)
                fh.write("\n")
            done += 1
    extra = set(T) - seen
    if extra:
        sys.exit("translations for missing files: " + ", ".join(sorted(extra)))
    with open(os.path.join(DST, "language.lang"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(LANG)
    with open(os.path.join(DST, "appearance.json"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(APPEARANCE + "\n")
    print("pages:", done)


main()
